import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'vite';

const root = resolve(import.meta.dirname, '..');
const docs = resolve(root, 'docs');
const host = '<div class="amb-docs-footer-host"></div>';
const stylesheet = '<link rel="stylesheet" href="./amb-footer/footer.css">';
const script = '<script type="module" src="./amb-footer/footer.js"></script>';
const standardFooter = /<footer>\s*Documentation generated by <a href="https:\/\/github\.com\/jsdoc\/jsdoc">JSDoc [^<]+<\/a> on [^<]+\s*<\/footer>/g;
const pages = (await readdir(docs, { withFileTypes: true }))
    .filter(entry => entry.isFile() && entry.name.endsWith('.html'))
    .map(entry => entry.name).sort();

if (!pages.length) throw new Error('No generated JSDoc HTML pages found');

const updates = [];
for (const page of pages) {
    const path = resolve(docs, page);
    const html = await readFile(path, 'utf8');
    const existing = html.split(host).length - 1;
    const matches = [...html.matchAll(standardFooter)];
    if (existing === 1 && matches.length === 0) {
        if (html.split(stylesheet).length !== 2 || html.split(script).length !== 2
            || /<footer\b/i.test(html)) {
            throw new Error(`Incomplete footer integration in ${page}`);
        }
        continue;
    }
    if (existing !== 0 || matches.length !== 1 || (html.match(/<footer\b/gi) || []).length !== 1
        || html.includes(stylesheet) || html.includes(script)
        || (html.match(/<\/head>/g) || []).length !== 1 || (html.match(/<\/body>/g) || []).length !== 1) {
        throw new Error(`Unexpected JSDoc structure in ${page}`);
    }
    updates.push([path, html.replace(standardFooter, host)
        .replace('</head>', `    ${stylesheet}\n</head>`)
        .replace('</body>', `${script}\n</body>`)]);
}

await build({
    configFile: false,
    root,
    publicDir: false,
    base: './',
    logLevel: 'warn',
    build: {
        outDir: resolve(docs, 'amb-footer'),
        emptyOutDir: true,
        assetsInlineLimit: 0,
        rollupOptions: {
            input: resolve(root, 'src/demo/docs-footer.js'),
            output: {
                entryFileNames: 'footer.js',
                assetFileNames: asset => asset.names.some(name => name.endsWith('.css'))
                    ? 'footer.css' : '[name][extname]'
            }
        }
    }
});

for (const [path, html] of updates) await writeFile(path, html);
console.log(`JSDoc footer integrated in ${pages.length} pages.`);
