const callCellState = (
    rowMethods,
    rowIdentifier,
    column,
    methodName,
    normalize = value => value
) => {
    const cell = rowMethods?.getRowCell?.(
        rowIdentifier,
        column
    );

    if (
        !cell
        || typeof cell[methodName] !== 'function'
    ) {
        return false;
    }

    return normalize(
        cell[methodName]()
    );
};

/**
 * Creates the runtime cell-state methods exposed by the AMB Grid
 * controller.
 *
 * @param {object} context - Required method dependencies.
 * @param {object} context.table - Grid table instance.
 * @param {object} context.rowMethods - AMB Grid row methods.
 * @returns {object} Cell-state methods for the flat controller API.
 * @private
 * @internal
 */
export const createCellStateMethods = ({ table, rowMethods }) => ({
    /**
     * Clears the grid's native edited marker from one or more cells.
     *
     * Pass a cell component, an array of cell components, or omit the argument
     * to clear all cells currently marked as edited by the grid.
     *
     * Clearing the native marker does not restore previous values and does not
     * reset AMB Grid row state, snapshots or save-payload information.
     *
     * Native editing and validation events generated by the grid remain under
     * the control of the runtime engine.
     *
     * @param {object|object[]} [cells] - Cell component or cells to clear.
     * @returns {void}
     */
    clearCellEdited(...args) {
        return table.clearCellEdited(...args);
    },

    /**
     * Resolves one Cell Component and clears only its native edited marker.
     * This does not restore its value or change AMB Grid CRUD state or payload;
     * returns `true` when delegated and `false` when unavailable.
     *
     * @param {*} rowIdentifier - AMB Grid row identifier.
     * @param {*} column - Supported column lookup.
     * @returns {boolean} Whether marker cleanup was delegated.
     */
    clearCellEditedMarker(rowIdentifier, column) {
        return callCellState(
            rowMethods,
            rowIdentifier,
            column,
            'clearEdited',
            () => true
        );
    },

    /**
     * Clears the grid's native validation marker from one or more cells.
     *
     * Pass a cell component, an array of cell components, or omit the argument
     * to clear all cells currently marked as invalid by the grid.
     *
     * The operation does not run a new validation pass and does not clear AMB
     * Grid `_errors`, validation messages or application-level row state.
     *
     * @param {object|object[]} [cells] - Cell component or cells to clear.
     * @returns {void}
     */
    clearCellValidation(...args) {
        return table.clearCellValidation(...args);
    },

    /**
     * Clears only the native validation marker of one AMB-resolved cell.
     * This does not run validation or clear AMB Grid errors; returns `true`
     * when delegated and `false` when unavailable.
     *
     * @param {*} rowIdentifier - AMB Grid row identifier.
     * @param {*} column - Supported column lookup.
     * @returns {boolean} Whether marker cleanup was delegated.
     */
    clearCellValidationMarker(rowIdentifier, column) {
        return callCellState(
            rowMethods,
            rowIdentifier,
            column,
            'clearValidation',
            () => true
        );
    },

    /**
     * Returns the cell components currently marked as edited by the grid.
     *
     * This native editing list is separate from AMB Grid row state, snapshots
     * and save payload generation. The returned array and cell components
     * retain their runtime identities and should be treated carefully.
     *
     * @returns {object[]} Cell components currently marked as edited.
     */
    getEditedCells() {
        return table.getEditedCells();
    },

    /**
     * Reads the native runtime edited marker of one managed cell component.
     *
     * The AMB Grid controller resolves the cell through an AMB Grid row
     * identifier and a supported column lookup. The marker is separate from
     * CRUD state and save-payload membership, and reading it does not modify
     * the cell value.
     *
     * @param {*} rowIdentifier - AMB Grid row identifier.
     * @param {*} column - Supported column lookup.
     * @returns {boolean} `true` when edited; `false` when not edited or when the cell or operation is unavailable.
     */
    isCellEdited(rowIdentifier, column) {
        return callCellState(
            rowMethods,
            rowIdentifier,
            column,
            'isEdited'
        );
    },

    /**
     * Returns the cell components currently marked as invalid by the grid's
     * native validation state.
     *
     * This list is separate from AMB Grid validation errors and `_errors`
     * metadata. The method reads the current native state without triggering a
     * new validation pass.
     *
     * @returns {object[]} Cell components currently marked as invalid.
     */
    getInvalidCells() {
        return table.getInvalidCells();
    },

    /**
     * Reads the previously calculated native runtime validation state of one
     * managed cell component.
     *
     * The AMB Grid controller resolves the cell through an AMB Grid row
     * identifier and a supported column lookup. No new validation is run:
     * `true` indicates a valid runtime state, while an array identifies the
     * failed validators. `false` means that the cell or operation is
     * unavailable.
     *
     * This result is not an AMB Grid validation report and does not replace
     * `validate()`, `validateRow()` or `validateChanges()` for application-level
     * AMB Grid validation.
     *
     * @param {*} rowIdentifier - AMB Grid row identifier.
     * @param {*} column - Supported column lookup.
     * @returns {boolean|object[]} Native state result, failed validators by identity, or `false` when unavailable.
     */
    isCellValid(rowIdentifier, column) {
        return callCellState(
            rowMethods,
            rowIdentifier,
            column,
            'isValid'
        );
    }
});
